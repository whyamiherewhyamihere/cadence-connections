<?php

// Открываем PHP-сессию для проверки доступа к заказу и работы с корзиной.
session_start();

// Подключаем загрузчик Composer и библиотеку Stripe.
require_once __DIR__ . '/../vendor/autoload.php';

// Подключаем общие функции проверки платежа и очистки корзины.
require_once __DIR__ . '/../lib/stripe_payment.php';

// Просим браузер и промежуточные кеши не сохранять ответ этой страницы.
header('Cache-Control: no-store');

// Запрещаем передавать адрес этой страницы в заголовке Referer.
// Адрес содержит идентификатор платежной сессии Stripe.
header('Referrer-Policy: no-referrer');

// Здесь будет найденный и проверенный заказ.
$order = null;

// Здесь будет сообщение об ошибке для отображения посетителю.
$error = '';

try {
    // Получаем идентификатор Stripe из адресной строки после возврата с оплаты.
    $sessionId = $_GET['session_id'] ?? '';

    // Проверяем тип, длину и формат идентификатора тестовой Checkout Session.
    if (
        !is_string($sessionId) // Значение должно быть строкой.
        || strlen($sessionId) > 255 // Ограничиваем длину входного значения.
        || !preg_match('/\Acs_test_[A-Za-z0-9_]+\z/', $sessionId) // Проверяем всю строку.
    ) {
        // Указываем, что запрос содержит некорректные данные.
        http_response_code(400);

        // Передаем понятное сообщение в обработчик исключения.
        throw new InvalidArgumentException('Некорректная ссылка оплаты.');
    }

    // Получаем PDO-подключение к PostgreSQL.
    $pdo = require __DIR__ . '/../config/db.php';

    // Ищем заказ по сохраненному идентификатору платежной сессии.
    $get = $pdo->prepare(
        'SELECT * FROM orders WHERE stripe_session_id = :session'
    );

    // Передаем идентификатор отдельно от текста SQL-запроса.
    $get->execute(['session' => $sessionId]);

    // Получаем запись заказа; если ее нет, используем null.
    $order = $get->fetch() ?: null;

    // Получаем токен доступа к этому заказу из PHP-сессии посетителя.
    // checkout.php записал его при оформлении заказа.
    // Если заказ не найден или токен отсутствует, используем пустую строку.
    $access = $order
        ? ($_SESSION['stripe_orders'][$order['id']] ?? '')
        : '';

    // Проверяем наличие заказа и совпадение токена доступа.
    // Одного идентификатора Stripe в URL недостаточно для просмотра заказа.
    if (
        !$order
        || !$access
        || !hash_equals($order['payment_access_token'], $access)
    ) {
        // Убираем найденные данные, чтобы не вывести их без проверки доступа.
        $order = null;

        // Возвращаем ответ о недоступности заказа.
        http_response_code(404);

        throw new InvalidArgumentException(
            'Заказ недоступен в этом браузере.'
        );
    }

    // Если заказ еще не отмечен как оплаченный, уточняем результат через API.
    // Это дополнительный путь подтверждения при задержке webhook.
    if ($order['payment_status'] !== 'paid') {
        // Загружаем локальные настройки Stripe.
        $config = require __DIR__ . '/../config/local.php';

        // Текущая интеграция допускает только тестовый секретный ключ.
        if (!str_starts_with($config['stripe_secret_key'] ?? '', 'sk_test_')) {
            throw new RuntimeException('Test API key required.');
        }

        // Создаем клиент для обращения к Stripe API.
        $stripe = new \Stripe\StripeClient(
            $config['stripe_secret_key']
        );

        // Получаем актуальное состояние уже существующей Checkout Session.
        // Новая платежная сессия на этой странице не создается.
        $checkout = $stripe->checkout->sessions->retrieve(
            $sessionId,
            []
        );

        // Преобразуем ответ Stripe в массив и передаем общей функции.
        // Она проверит связь с заказом, сумму, валюту и обновит запись в базе.
        $order = cadenceApplyPaymentSession(
            $pdo,
            $checkout->toArray()
        );
    }

    // Убеждаемся, что после обработки у нас есть запись заказа.
    if (!$order) {
        throw new RuntimeException('Order not found.');
    }

    // Очищаем корзину только для оплаченного заказа с совпадающим составом.
    // Если покупатель изменил корзину во время оплаты, функция сохранит ее.
    cadenceFinishCart($order);

} catch (InvalidArgumentException $e) {
    // Сохраняем понятное сообщение о некорректной ссылке или отсутствии доступа.
    $error = $e->getMessage();

} catch (Throwable $e) {
    // Записываем тип технической ошибки в серверный журнал.
    // Полный ответ Stripe и секретные настройки сюда не выводим.
    error_log('Cadence payment status failed: ' . get_class($e));

    // Показываем посетителю общее сообщение вместо технических подробностей.
    $error = 'Не удалось обновить статус оплаты. '
        . 'Обновите страницу через несколько секунд.';
}

// Определяем, можно ли показывать подтверждение оплаты.
// Заказ должен существовать и иметь подтвержденный статус paid.
$paid = $order !== null && $order['payment_status'] === 'paid';

// Подключаем общую шапку после подготовки данных и HTTP-заголовков.
require_once __DIR__ . '/../components/header.php';

?>

<!-- Основное содержимое страницы результата оплаты. -->
<main class="order-success-main">
    <section class="order-success">

        <!-- Заголовок зависит от подтвержденного состояния заказа. -->
        <h2><?= $paid ? 'ЗАКАЗ ОПЛАЧЕН' : 'СТАТУС ОПЛАТЫ' ?></h2>

        <!-- При ошибке показываем сообщение вместо сведений о результате. -->
        <?php if ($error !== ''): ?>

            <!-- Экранируем сообщение, чтобы оно отображалось как текст. -->
            <p><?= htmlspecialchars($error, ENT_QUOTES, 'UTF-8') ?></p>

        <!-- Если ошибок нет и статус paid, показываем подтверждение. -->
        <?php elseif ($paid): ?>
            <p>
                <!-- Приводим номер заказа к целому числу перед выводом. -->
                Тестовая оплата заказа №<?= (int) $order['id'] ?>
                подтверждена.
            </p>

            <!-- Форматируем сохраненную сумму для отображения с двумя знаками. -->
            <!-- Приведение к float здесь используется только для вывода. -->
            <p>
                Сумма:
                <?= number_format((float) $order['total_price'], 2, ',', ' ') ?> ₽
            </p>

        <!-- Для остальных состояний не показываем успешную оплату. -->
        <?php else: ?>
            <p>Оплата пока не подтверждена.</p>

            <!-- Показываем текущий статус из проверенной записи заказа. -->
            <p>
                Статус:
                <?= htmlspecialchars($order['payment_status'], ENT_QUOTES, 'UTF-8') ?>
            </p>

            <p>Обновите страницу через несколько секунд.</p>
        <?php endif; ?>

        <!-- Ссылка возвращает посетителя на главную страницу магазина. -->
        <a href="index1.php">Вернуться в магазин</a>
    </section>
</main>

<?php
// Подключаем общий подвал сайта.
require_once __DIR__ . '/../components/footer.php';
?>