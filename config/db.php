<?php

// Загружаем настройки подключения из файла local.php.
// Этот файл возвращает массив с адресом сервера, портом,
// названием базы, именем пользователя и паролем.
//
// __DIR__ — абсолютный путь к папке текущего файла, то есть config.
// Поэтому путь не зависит от того, какой PHP-файл вызвал подключение.
$config = require __DIR__ . '/local.php';

// Формируем DSN — строку, которая описывает подключение к базе.
//
// pgsql — используем драйвер PostgreSQL.
// host — адрес сервера базы данных.
// port — порт PostgreSQL.
// dbname — название базы данных.
//
// sprintf подставляет значения вместо обозначений:
// %s — строка;
// %d — целое число.
$dsn = sprintf(
    'pgsql:host=%s;port=%d;dbname=%s',
    $config['db_host'],
    $config['db_port'],
    $config['db_name']
);

// Создаем подключение к PostgreSQL и возвращаем объект PDO.
//
// В других файлах подключение можно получить так:
// $pdo = require __DIR__ . '/../config/db.php';
//
// Если подключиться не получится, конструктор PDO выбросит исключение.
return new PDO(
    // Строка подключения: драйвер, адрес, порт и название базы.
    $dsn,

    // Пользователь PostgreSQL, от имени которого выполняются запросы.
    $config['db_user'],

    // Пароль этого пользователя.
    $config['db_password'],

    // Настройки работы PDO.
    [
        // При ошибке SQL-запроса выбрасываем исключение PDOException.
        // Это позволяет обработать ошибку в try/catch
        // и при необходимости откатить транзакцию.
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,

        // По умолчанию получаем строки как ассоциативные массивы.
        // Например, к полю заказа обращаемся через $order['id'].
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,

        // Отключаем эмуляцию подготовленных запросов на стороне PDO.
        // Используем подготовку запросов средствами драйвера PostgreSQL.
        //
        // Значения передаем отдельно через execute(), например:
        // $query = $pdo->prepare('SELECT * FROM orders WHERE id = :id');
        // $query->execute(['id' => $orderId]);
        PDO::ATTR_EMULATE_PREPARES => false,
    ]
);